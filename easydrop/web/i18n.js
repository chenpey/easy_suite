const dictionaries = { zh, en };

export function getLanguage() {
  const lang = typeof localStorage !== "undefined" ? localStorage.getItem(languageKey) : null;
  return lang === "en" ? "en" : "zh";
}

export function setLanguage(language) {
  if (typeof localStorage !== "undefined") {
    localStorage.setItem(languageKey, language === "en" ? "en" : "zh");
    location.reload();
  }
}

export const uiLanguage = getLanguage();
export const dateLocale = uiLanguage === "en" ? "en-US" : "zh-CN";

export function t(key, ...args) {
  const dict = dictionaries[uiLanguage] || dictionaries.zh;
  const pattern = dict[key] ?? dictionaries.zh[key] ?? key;
  if (!args.length) return pattern;
  return pattern.replace(/\{(\d+)\}/g, (_, index) => args[Number(index)] ?? `{${index}}`);
}

export function renderStaticI18n(root = document) {
  document.documentElement.lang = uiLanguage === "en" ? "en" : "zh-CN";

  const metaDesc = root.querySelector?.('meta[name="description"]');
  if (metaDesc && metaDesc.hasAttribute("data-i18n-content")) {
    metaDesc.setAttribute("content", t(metaDesc.getAttribute("data-i18n-content")));
  }

  const titleEl = root.querySelector?.("title[data-i18n]");
  if (titleEl) {
    document.title = t(titleEl.getAttribute("data-i18n"));
  }

  for (const el of root.querySelectorAll("[data-i18n]")) {
    if (el.tagName === "TITLE") continue;
    el.textContent = t(el.getAttribute("data-i18n"));
  }

  for (const attr of ["placeholder", "title", "aria-label", "alt"]) {
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) {
      el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
    }
  }
}
